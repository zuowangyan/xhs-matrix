// 精简中文停用词 + 小红书评论常见无意义词，用于评论痛点聚类时过滤噪声。
export const STOPWORDS = new Set<string>([
  "的", "了", "和", "是", "在", "我", "有", "也", "就", "都", "而", "及", "与", "着",
  "或", "一个", "没有", "我们", "你们", "他们", "自己", "这个", "那个", "什么", "怎么",
  "可以", "这样", "那样", "因为", "所以", "但是", "如果", "虽然", "请问", "谢谢", "姐妹",
  "真的", "感觉", "觉得", "现在", "已经", "还是", "不是", "就是", "这么", "那么", "一下",
  "他", "她", "它", "你", "啊", "吧", "呢", "吗", "哦", "呀", "嘛", "哈", "哈哈", "嗯",
  "一", "二", "三", "不", "很", "太", "更", "多", "少", "好", "大", "小", "上", "下",
  "想", "要", "能", "会", "到", "说", "看", "用", "买", "喝", "吃", "求", "问",
  // 评论高频疑问/填充词（非痛点本身）
  "怎么样", "会不会", "有没有", "是不是", "可不可以", "行不行", "一样", "还有",
  "这种", "那种", "一直", "一点", "之后", "之前", "时候", "知道", "应该", "为什么",
]);

export function isMeaningful(word: string, extraStop: Set<string>): boolean {
  const w = word.trim();
  if (w.length < 2) return false; // 过滤单字
  if (/^[\d\p{P}\s]+$/u.test(w)) return false; // 纯数字/标点/空白
  if (STOPWORDS.has(w)) return false;
  if (extraStop.has(w)) return false;
  return true;
}
